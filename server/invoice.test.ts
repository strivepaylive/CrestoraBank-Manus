import { describe, expect, it } from 'vitest';
import { generateInvoicePdf } from './invoicePdf';

const baseInvoice = {
  reference: 'INV-TEST-000001',
  clientName: 'Vitest Client',
  clientEmail: 'vitest@example.com',
  accountNumber: '1234567890',
  bankName: 'Crestora Bank',
  amount: '1250.00',
  currency: 'USD',
  description: 'Vitest invoice generation',
  dueDate: new Date('2026-08-31'),
  createdAt: new Date('2026-07-08'),
  customMessage: 'Generated by automated test.',
  topLogoUrl: null,
  bottomLogoUrl: null,
};

describe('Invoice PDF generation', () => {
  it('produces a valid PDF buffer', async () => {
    const buffer = await generateInvoicePdf(baseInvoice);
    expect(Buffer.isBuffer(buffer)).toBe(true);
    expect(buffer.length).toBeGreaterThan(1000);
    expect(buffer.subarray(0, 5).toString()).toBe('%PDF-');
  });

  it('handles invoices without a custom message', async () => {
    const buffer = await generateInvoicePdf({ ...baseInvoice, customMessage: null });
    expect(buffer.subarray(0, 5).toString()).toBe('%PDF-');
  });

  it('formats decimal string amounts without treating them as cents', async () => {
    const amountStr = `${baseInvoice.currency} ${parseFloat('250.00').toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    expect(amountStr).toBe('USD 250.00');
  });
});
